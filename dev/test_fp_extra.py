def build_pdf(path, paras):
    doc = pymupdf.open()
    page = doc.new_page(width=595, height=842)
    y = 70
    for t in paras:
        for i in range(0, len(t), 40):
            page.insert_text((56, y), t[i:i + 40], fontname="china-s", fontsize=10)
            y += 16
            if y > 790:
                page = doc.new_page(width=595, height=842)
                y = 70
    doc.save(path, deflate=True)
    doc.close()


def main():
    os.makedirs(os.path.join(HERE, "..", "test"), exist_ok=True)
    allok = True
    for name, paras in TEXTS.items():
        path = os.path.join(HERE, "..", "test", "误报_%s.pdf" % name)
        build_pdf(path, paras)
        doc = pymupdf.open(path)
        fs = pdfmask.detect(doc)
        txt = "".join(pg.get_text() for pg in doc).replace("\n", "")
        print("\n[%s] %d 字，检出 %d 处" % (name, len(txt), len(fs)))
        for f in fs:
            print("   误报? [%s] %r  (%s)" % (f["type"], f["text"], f["note"]))
        if fs:
            allok = False
    print("\n结论:", "全部干净" if allok else "存在误报")
    return 0 if allok else 1


if __name__ == "__main__":
    sys.exit(main())
