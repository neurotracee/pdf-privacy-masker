def wrap(text, width=38):
    lines, i = [], 0
    while i < len(text):
        lines.append(text[i:i + width])
        i += width
    return lines


def main():
    doc = pymupdf.open()
    page = doc.new_page(width=595, height=842)
    y = 60
    for para in PARAS:
        if not para:
            y += 12
            continue
        for ln in wrap(para):
            if y > 800:
                page = doc.new_page(width=595, height=842)
                y = 60
            page.insert_text((50, y), ln, fontname="china-s", fontsize=11)
            y += 20
    from _testpaths import out as _out_path
    out = _out_path("纯净文档_无隐私.pdf")
    doc.save(out)
    doc.close()

    d, fs = pdfmask.detect_document(out)
    body = "".join(p.get_text() for p in d).replace("\n", "").replace(" ", "")
    print("文档字数:", len(body), "页数:", d.page_count)
    print("检出总数:", len(fs))
    for f in fs:
        print("  [误判] %-6s %r  上下文: %r" % (
            pdfmask.TYPE_NAME[f["type"]], f["text"],
            body[max(0, 0):0] or ""))
    if not fs:
        print("  该文件不含任何个人信息，程序检出 0 处 —— 没有无中生有。")
    sys.exit(0 if not fs else 1)


